"""Build the real-world benchmark corpus and its workflow.

For each public repository known to run xu-cheng/latex-action successfully,
read its workflow, keep the latex-action step's inputs when they are static
(no ${{ }} expressions), and pin the current commit. Then write
bench/corpus.json and .github/workflows/bench-corpus.yml, which runs every
entry with the incumbent and with this action, passing identical inputs.

Entries with a "group" field are added by hand (repositories without a
latex-action workflow, such as Japanese thesis templates) and are kept.

Usage: python3 tools/make_corpus.py REPOS_TSV   (or --regen to rebuild the workflow from bench/corpus.json)
  REPOS_TSV: lines "owner/repo<TAB>workflow-file-name" (extra columns ignored).
Requires an authenticated `gh`.
"""
import base64
import json
import re
import subprocess
import sys

import yaml

COMPAT_INPUTS = [
    "root_file", "working_directory", "work_in_root_file_dir", "compiler", "args",
    "latexmk_use_xelatex", "latexmk_use_lualatex", "latexmk_shell_escape",
    "extra_system_packages", "extra_fonts", "pre_compile", "post_compile",
    "continue_on_error", "texlive_version",
]


def gh(*args):
    return subprocess.run(["gh", "api", *args], capture_output=True, text=True, check=True).stdout


def latex_steps(workflow):
    for job in (workflow.get("jobs") or {}).values():
        for step in job.get("steps") or []:
            uses = str(step.get("uses", ""))
            if uses.startswith("xu-cheng/latex-action@"):
                yield step


def checkout_path(workflow):
    """Where the job that runs the latex step checks the repository out (with: path)."""
    for job in (workflow.get("jobs") or {}).values():
        steps = job.get("steps") or []
        if not any(str(s.get("uses", "")).startswith("xu-cheng/latex-action@") for s in steps):
            continue
        for s in steps:
            w = s.get("with") or {}
            if str(s.get("uses", "")).startswith("actions/checkout@") and "repository" not in w and w.get("path"):
                return str(w["path"])
    return None


def entry_for(repo, wf_name):
    meta = json.loads(gh(f"repos/{repo}"))
    branch = meta["default_branch"]
    sha = json.loads(gh(f"repos/{repo}/commits/{branch}"))["sha"]
    content = json.loads(gh(f"repos/{repo}/contents/.github/workflows/{wf_name}?ref={sha}"))
    workflow = yaml.safe_load(base64.b64decode(content["content"]).decode("utf-8"))
    steps = list(latex_steps(workflow))
    if len(steps) != 1:
        return None, f"{len(steps)} latex-action steps"
    inputs = {k: v for k, v in (steps[0].get("with") or {}).items()}
    if any("${{" in str(v) for v in inputs.values()):
        return None, "inputs use expressions"
    unknown = set(inputs) - set(COMPAT_INPUTS)
    if unknown:
        return None, f"inputs {sorted(unknown)}"
    if "docker_image" in inputs:
        return None, "custom docker image"
    clean = {}
    for k, v in inputs.items():
        clean[k] = ("true" if v else "false") if isinstance(v, bool) else str(v)
    ident = re.sub(r"[^a-z0-9]+", "-", repo.lower()).strip("-")
    entry = {"id": ident, "repo": repo, "sha": sha, "with": clean}
    path = checkout_path(workflow)
    if path:
        entry["checkout_path"] = path
    return entry, None


def yaml_with(inputs, indent):
    pad = " " * indent
    lines = []
    for k, v in inputs.items():
        if "\n" in v:
            lines.append(f"{pad}{k}: |")
            lines.extend(f"{pad}  {line}" for line in v.rstrip("\n").split("\n"))
        else:
            lines.append(f"{pad}{k}: {json.dumps(v)}")
    return "\n".join(lines)


def workflow(entries):
    out = [
        "# Generated by tools/make_corpus.py. Do not edit by hand.",
        "name: Benchmark · real-world corpus",
        "",
        "on:",
        "  workflow_dispatch:",
        "    inputs:",
        "      only:",
        "        description: Comma-separated entry ids to run (empty = all)",
        "        default: \"\"",
        "",
        "permissions:",
        "  contents: read",
        "  actions: read",
        "",
        "jobs:",
    ]
    for e in entries:
        for variant in ("incumbent", "ours"):
            out += [
                f"  {variant}-{e['id']}:",
                f"    name: {variant} · {e['id']}",
                f"    if: ${{{{ inputs.only == '' || contains(format(',{{0}},', inputs.only), ',{e['id']},') }}}}",
                "    runs-on: ubuntu-latest",
                *(["    continue-on-error: true  # it fails on some entries by design; only this action's jobs decide the run"] if variant == "incumbent" else []),
                "    timeout-minutes: 30",
                "    steps:",
                "      - uses: actions/checkout@v5",
                "        with:",
                f"          repository: {e['repo']}",
                f"          ref: {e['sha']}",
                "          submodules: recursive",
            ]
            if e.get("checkout_path"):
                out.append(f"          path: {e['checkout_path']}")
            if variant == "incumbent":
                out.append("      - uses: xu-cheng/latex-action@v4")
            else:
                out += [
                    "      - uses: actions/checkout@v5",
                    "        with:",
                    "          path: .ofree-engine",
                    "      - uses: ./.ofree-engine",
                ]
            if e["with"]:
                out.append("        with:")
                out.append(yaml_with(e["with"], 10))
            out.append("")
    needs = ", ".join(f"{v}-{e['id']}" for e in entries for v in ("incumbent", "ours"))
    out += [
        "  results:",
        f"    needs: [{needs}]",
        "    if: always()",
        "    runs-on: ubuntu-latest",
        "    steps:",
        "      - uses: actions/checkout@v5",
        "      - env:",
        "          GH_TOKEN: ${{ github.token }}",
        "        run: python3 tools/bench_results.py >> \"$GITHUB_STEP_SUMMARY\"",
        "",
    ]
    return "\n".join(out)


def main():
    if sys.argv[1] == "--regen":
        entries = json.load(open("bench/corpus.json"))
        open(".github/workflows/bench-corpus.yml", "w").write(workflow(entries))
        print(f"regenerated the workflow for {len(entries)} entries")
        return
    seen, entries, skipped = set(), [], []
    for line in open(sys.argv[1]):
        repo, wf_name = line.rstrip("\n").split("\t")[:2]
        if (repo, wf_name) in seen:
            continue
        seen.add((repo, wf_name))
        try:
            entry, why = entry_for(repo, wf_name)
        except subprocess.CalledProcessError as err:
            entry, why = None, f"API error: {err.stderr.strip()[:80]}"
        if entry:
            entries.append(entry)
        else:
            skipped.append((repo, why))
    # Hand-picked entries (with a "group", e.g. Japanese templates without a workflow) are kept.
    try:
        entries += [e for e in json.load(open("bench/corpus.json")) if e.get("group")]
    except FileNotFoundError:
        pass
    ids = set()
    for e in entries:
        while e["id"] in ids:
            e["id"] += "-2"
        ids.add(e["id"])
    json.dump(entries, open("bench/corpus.json", "w"), indent=1)
    open(".github/workflows/bench-corpus.yml", "w").write(workflow(entries))
    print(f"{len(entries)} entries; skipped {len(skipped)}:")
    for repo, why in skipped:
        print(f"  {repo}: {why}")


if __name__ == "__main__":
    main()
